import fs from 'node:fs';
import assert from 'node:assert/strict';
const read=(p)=>fs.readFileSync(p,'utf8');
const app=read('apps/fueltrack-plus/app.v3.17.0-wm6.js');
const domain=read('apps/fueltrack-plus/domain-config.js');
const css=read('apps/fueltrack-plus/styles.v3.17.0-wm6.css');
const runtime=read('apps/fueltrack-plus/runtime.html');
const store=read('assets/js/core/module-cloud-store.ts');
const migration=read('supabase/migrations/v1.18.0-activity-triage-workspace.sql');
const schema=read('supabase/schema.sql');
assert.ok(runtime.includes('app.v3.17.0-wm6.js') && runtime.includes('styles.v3.17.0-wm6.css'),'runtime must use wm6 Activity assets');
assert.ok(domain.includes('fueltrackplus.activity.workspace.v1'),'Activity workspace cloud key missing from FuelTrack domain boundary');
assert.ok(store.includes("'fueltrackplus.activity.workspace.v1'"),'Activity workspace must be user scoped in cloud adapter');
assert.ok(migration.includes("'fueltrackplus.activity.workspace.v1'") && migration.includes("'user'"),'Activity workspace policy migration missing');
assert.ok(schema.includes("'fueltrackplus.activity.workspace.v1','exact','user'"),'fresh schema missing Activity workspace policy');
assert.ok(app.includes('Archive for me') && app.includes('Restore to Timeline'),'personal archive/restore actions missing');
assert.ok(app.includes('activitySelectedIds') && app.includes('activity-bulk-archive') && app.includes('activity-bulk-restore'),'bulk Activity triage missing');
assert.ok(app.includes('activity-view-tabs') && app.includes('data-activity-view="archived"'),'Timeline/Archived views missing');
assert.ok(app.includes('The shared audit record was not deleted') && app.includes('Append-only shared audit stream'),'audit immutability language missing');
assert.ok(!app.includes('removeItem(KEYS.activity'),'Activity audit stream must never be deleted by triage UI');
assert.ok(css.includes('.activity-more-popover') && css.includes('.activity-selection-bar') && css.includes('.activity-view-tabs'),'Activity contextual interaction styles missing');
assert.ok(css.includes('@media(max-width:900px)'),'Activity triage responsive behavior missing');
console.log('v1.18.0 Activity triage verification: PASS');
