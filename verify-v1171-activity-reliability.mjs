import fs from 'node:fs';
import assert from 'node:assert/strict';
const read=(p)=>fs.readFileSync(p,'utf8');
const fuel=read('apps/fueltrack-plus/app.v3.17.0-wm6.js');
const fuelDomain=read('apps/fueltrack-plus/domain-config.js');
const css=read('apps/fueltrack-plus/styles.v3.17.0-wm6.css');
const html=read('apps/fueltrack-plus/runtime.html');
const tt=read('apps/time-tracker/app.js');
const platform=read('assets/js/core/platform.ts');
const sw=read('service-worker.js');
assert.ok(html.includes('app.v3.17.0-wm6.js') && html.includes('styles.v3.17.0-wm6.css'),'FuelTrack runtime must use cache-coherent v1.17.1 assets');
assert.ok(fuelDomain.includes('ACTIVITY_REFRESH_INTERVAL_MS = 20000'),'Activity refresh policy missing from FuelTrack domain boundary');
for(const marker of ['refreshActivityStream','configureActivityAutoRefresh','activitySyncStatus','queueActivityFilterPersistence','activityTimeLabel','preserveScroll']) assert.ok(fuel.includes(marker),`Activity reliability marker missing: ${marker}`);
assert.ok(fuel.includes('JSON.stringify(a.payload||{})'),'Activity search must include structured payload');
assert.ok(fuel.includes('aria-busy="${state.activitySyncStatus'), 'Activity timeline must expose refresh busy state');
assert.ok(css.includes('.activity-sync-status') && css.includes('prefers-reduced-motion'),'Activity sync feedback/accessibility styles missing');
assert.ok(tt.includes("commitAuthoritativeAttendance('clock-in'"),'TimeTracker Clock In must use the server transaction boundary');
assert.ok(!tt.includes('recoverAfterAttendanceLockCollision'),'Obsolete attendance lease-collision recovery must be removed');
assert.ok(platform.includes("PLATFORM_VERSION = '1.43.2'"),'Platform version mismatch');
assert.ok(sw.includes('work-management-v1.43.2'),'Service worker cache mismatch');
console.log('v1.17.1-activity-reliability-verification: PASS');
