import fs from 'node:fs';
const read=(f)=>fs.readFileSync(f,'utf8');
const manifest=read('config/application-manifest.ts');
const platform=read('assets/js/core/platform.ts');
const sw=read('service-worker.js');
const view=read('assets/js/features/boards/views/item-workspace-view.ts');
const renderer=read('assets/js/features/boards/controllers/item-panel-renderer.ts');
const controller=read('assets/js/features/boards/controllers/item-workspace-controller.ts');
const runtime=read('assets/js/features/boards/services/item-workspace-runtime.ts');
const board=read('assets/js/boards-ui.ts');
const css=read('assets/css/app.css');
const browser=read('tests/browser/run-cdp.mjs');
const menuController=read('assets/js/features/boards/controllers/board-menu-controller.ts');
const must=(v,m)=>{if(!v)throw new Error(m)};
must(manifest.includes("version: '1.43.2'"),'manifest version');
must(platform.includes("PLATFORM_VERSION = '1.43.2'"),'platform version');
must(sw.includes('work-management-v1.43.2'),'service worker cache');
must(manifest.includes("'item-panel-renderer'"),'Board manifest declares stable Item Workspace renderer');
must(view.includes('data-item-id="${esc(item.id)}"') && view.includes('data-active-tab="${tab}"'),'workspace shell identifies item and active tab');
must(view.includes('data-item-panel-body') && view.includes('data-item-tab-stage'),'view separates stable scroll viewport from replaceable tab stage');
must(renderer.includes('currentPanel.dataset.itemId !== nextPanel.dataset.itemId'),'renderer only remounts shell for a different item');
must(renderer.includes('currentBody.replaceChildren(nextStage)'),'renderer replaces only internal stage');
must(renderer.includes('scrollByTab.set(previousTab, currentBody.scrollTop)'),'per-tab scroll memory');
must(renderer.includes('animation?.cancel()'),'in-flight transition cancellation');
must(renderer.includes('reducedMotion()'),'reduced-motion guard');
must(runtime.includes('if (state.itemPanel.tab === nextTab) return true;') && runtime.indexOf('if (state.itemPanel.tab === nextTab) return true;') < runtime.indexOf('notify();', runtime.indexOf('const setTab')), 'active-tab repeated click does not rerender');
must(controller.includes("['ArrowLeft', 'ArrowRight', 'Home', 'End'].includes(event.key)"),'keyboard tab navigation');
must(board.includes('createItemPanelRenderer') && board.includes('itemPanelRenderer.render(itemPanelMarkup())'),'Board uses stable renderer');
must(css.includes('.item-panel-tab-stage') && css.includes('overflow-anchor:none'),'stable content stage and scroll behavior');
must(view.includes('data-board-menu-trigger="item-panel"') && view.includes('data-board-menu-template'),'Item Workspace actions use unified Board floating menu');
must(!view.includes('<details class="context-menu item-panel-actions"'),'legacy drawer-local details menu removed');
must(menuController.includes("overlayLayer.className = 'board-overlay-layer'"),'Board menu controller owns dedicated overlay layer');
must(menuController.includes('overlayLayer.appendChild(menu)'),'floating menu renders in overlay layer rather than drawer/header');
must(css.includes('.board-overlay-layer') && css.includes('z-index:320'),'Board overlay layer sits above Item Workspace shell');
must(css.includes('.item-panel-more-trigger'),'Item Workspace action trigger has dedicated interaction styling');
must(browser.includes('tab switch keeps Item Workspace drawer shell mounted'),'browser shell identity regression coverage');
must(browser.includes('rapid tab switching settles on latest tab'),'rapid switching regression coverage');
must(browser.includes('reduced-motion tab switching starts no content animation'),'reduced motion browser coverage');
must(browser.includes('Item Workspace action menu overlays drawer chrome'),'drawer action overlay browser coverage');
must(!fs.existsSync('supabase/migrations/v1.32.4-item-workspace-tabs.sql'),'no unnecessary database migration');
console.log('v1.32.4 Item Workspace tab stability verification: PASS');
