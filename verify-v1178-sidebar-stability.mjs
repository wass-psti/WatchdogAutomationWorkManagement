import fs from 'node:fs';
import assert from 'node:assert/strict';
const css = fs.readFileSync(new URL('./assets/css/app.css', import.meta.url), 'utf8');
const app = fs.readFileSync(new URL('./assets/js/app.ts', import.meta.url), 'utf8');
const platform = fs.readFileSync(new URL('./assets/js/core/platform.ts', import.meta.url), 'utf8');
const sw = fs.readFileSync(new URL('./service-worker.js', import.meta.url), 'utf8');
assert.ok(platform.includes("PLATFORM_VERSION = '1.43.2'"), 'platform version mismatch');
assert.ok(sw.includes('work-management-v1.43.2'), 'service worker cache mismatch');
assert.ok(css.includes('--wm-sidebar-width:250px'), 'desktop sidebar token missing');
assert.ok(css.includes('position:fixed!important'), 'sidebar must be viewport-fixed');
assert.ok(css.includes('margin-left:var(--wm-sidebar-width)'), 'workspace desktop offset missing');
assert.ok(css.includes('margin-left:var(--wm-sidebar-compact-width)'), 'workspace compact offset missing');
assert.ok(css.includes('overflow-x:clip'), 'overflow clipping must not create a sticky-breaking overflow container');
assert.ok(css.includes('.sidebar nav{\n  flex:1 1 auto;'), 'sidebar nav must own remaining vertical space');
assert.ok(css.includes('overflow-y:auto'), 'short-viewport sidebar navigation must scroll independently');
assert.ok(css.includes('env(safe-area-inset-bottom)'), 'mobile navigation must account for safe area');
assert.ok(!/body\{[^}]*overflow-x:hidden/.test(css), 'body overflow-x:hidden reintroduces sticky/scroll-container defects');
assert.ok(app.includes('data-workspace-shell'), 'persistent shell contract missing');
console.log('v1.17.9 sidebar stability verification: PASS');
