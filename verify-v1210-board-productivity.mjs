import fs from 'node:fs';
import assert from 'node:assert/strict';
const read=(p)=>fs.readFileSync(p,'utf8');
const sql=read('supabase/migrations/v1.21.0-board-productivity.sql');
const schema=read('supabase/schema.sql');
const ui=read('assets/js/boards-ui.ts');
const workflows=read('assets/js/features/boards/controllers/column-workflows.ts');
const tableView=read('assets/js/features/boards/views/table-view.ts');
const service=read('assets/js/features/boards/data/board-repository.ts');
const css=read('assets/css/app.css');
for(const token of ['preferences jsonb','wm_get_board_preferences','wm_set_board_preferences','wm_add_board_column_at','wm_duplicate_board_column','wm_change_board_column_type']) assert.ok(sql.includes(token),`Missing ${token}`);
assert.ok(sql.includes("work_board_access(p_board_id,'view')"),'Preferences are not server-authorized');
assert.ok(sql.includes("work_board_access(c.board_id,'edit')"),'Column mutation authorization missing');
assert.ok(sql.includes("Core column types cannot be changed"),'Core type safeguard missing');
assert.ok(sql.includes("Choose to clear existing values"),'Type-change data-loss safeguard missing');
assert.ok(schema.includes('-- Work Management v1.21.0 — board column productivity and per-user view preferences'),'New-install schema missing v1.21 migration');
for(const fn of ['getPreferences','setPreferences','duplicateColumn','changeColumnType']) assert.ok(service.includes(`async ${fn}`),`Board service missing ${fn}`);
for(const token of ['columnHeader','data-column-filter','data-column-sort','data-column-wrap','data-column-duplicate','data-column-add-right','data-column-change-type','data-reset-board-view']) assert.ok(ui.includes(token),`Board interaction layer missing ${token}`);
for(const token of ['openFilter','openDuplicate','openChangeType']) assert.ok(workflows.includes(token),`Column workflow controller missing ${token}`);
assert.ok(ui.includes('persistBoardPrefs'),'Board preferences are not persisted');
assert.ok(tableView.includes('.sort(compareItems)'),'Column sorting is not applied to table rows');
for(const token of ['.column-context-menu','.column-context-pop','.board-data-cell.is-wrapped','.choice-card','.warning-panel']) assert.ok(css.includes(token),`Missing style ${token}`);
console.log('v1.21.0 board productivity verification: PASS');
